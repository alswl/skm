	output, err := exec.Command("git", "init", "-q", project).CombinedOutput()
	require.NoError(t, err, string(output))
	userDir := filepath.Join(project, ".agents", "skills")
	require.NoError(t, os.MkdirAll(userDir, 0o755))
	link := filepath.Join(userDir, "review")
	require.NoError(t, os.Symlink(skill, link))
	svc, err := New(&config.Config{Root: root, ConfigDir: t.TempDir(), Targets: []common.InstallTarget{skillTarget("codex", userDir)}}, common.NewLogger(false))
